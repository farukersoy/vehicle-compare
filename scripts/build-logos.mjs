#!/usr/bin/env node
/**
 * Builds src/data/brand-logos.ts from the Simple Icons library (CC0).
 *
 *   node scripts/build-logos.mjs
 *
 * Reads the distinct brands from src/data/vehicles.ts, maps each one to a
 * Simple Icons slug via scripts/logo-slugs.json and writes one SVG path per
 * brand (viewBox 0 0 24 24). Brands without a slug (null) or with a slug the
 * library does not have are left out; the app shows a monogram for them.
 * simple-icons is a devDependency used only here, never imported by app code.
 */

import fs from 'node:fs/promises'
import * as icons from 'simple-icons'
import { loadTsModule, readJson, p } from './lib/common.mjs'

const { vehicles } = await loadTsModule(p('src/data/vehicles.ts'))
const slugs = await readJson(p('scripts/logo-slugs.json'), {})
const bySlug = new Map(Object.values(icons).filter((i) => i && i.slug).map((i) => [i.slug, i]))
const pkg = JSON.parse(await fs.readFile(p('node_modules/simple-icons/package.json'), 'utf8'))

const brands = [...new Set(vehicles.map((v) => v.brand))].sort((a, b) => a.localeCompare(b))
const logos = {}
const report = { logo: [], monogram: [], unmapped: [] }

for (const brand of brands) {
  if (!(brand in slugs)) { report.unmapped.push(brand); report.monogram.push(brand); continue }
  const slug = slugs[brand]
  const icon = slug ? bySlug.get(slug) : null
  if (icon) { logos[brand] = icon.path; report.logo.push(`${brand} (${slug})`) }
  else { report.monogram.push(slug ? `${brand} (slug "${slug}" not in simple-icons ${pkg.version})` : brand) }
}

const out = `// GENERATED by scripts/build-logos.mjs — do not edit by hand.
// Brand logo shapes from Simple Icons ${pkg.version} (https://simpleicons.org, CC0 1.0).
// One SVG path per brand, viewBox 0 0 24 24, drawn with fill="currentColor".
// Brands not listed here are shown as a monogram (see components/BrandLogo).
// Brand names and logos belong to their respective owners; identification only.

export const BRAND_LOGO_PATHS: Record<string, string> = ${JSON.stringify(logos, null, 2)}
`
await fs.writeFile(p('src/data/brand-logos.ts'), out)

console.log(`Brands: ${brands.length}`)
console.log(`Logo (${report.logo.length}): ${report.logo.join(', ')}`)
console.log(`Monogram (${report.monogram.length}): ${report.monogram.join(', ')}`)
if (report.unmapped.length) console.log(`Not in logo-slugs.json (add them): ${report.unmapped.join(', ')}`)
